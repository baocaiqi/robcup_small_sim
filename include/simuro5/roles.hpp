// ============================================================
#ifndef SIMURO5_ROLES_HPP
#define SIMURO5_ROLES_HPP

#include "simuro5/world_model.hpp"

namespace simuro5 {

// ============================================================
// 第 49 轮「推球守卫」总开关（2026-09-12 正式落入主分支）
// ------------------------------------------------------------
//   true  = 第 49 轮原行为：**死球/摆位期 或 球在四角黄区内** → 一律不碰球
//           （治平台 `No pushing` 犯规：每 4 次白送对手 1 球）。
//           代价：角上的球没人碰、观感被动（实测"球推到门前没人管"）。
//   false = 等于 9/11「连胜版 38E8389E」的行为（真机 5 场胜利那一版）。
//
//   真机取舍依据（docs/06 第 50/51 轮、docs/21）：
//     守卫开：停表 8.6~19.0 次/分 → 1.1~6.1 次/分；但黄队纪律版胜率不及连胜版
//     守卫关：回到连胜版行为（用户拍板口径：先要成绩）
//   若后续 `No pushing` 犯规回升（4 次 = 1 球），把这里改回 true 即可，其它代码不用动。
// ============================================================
constexpr bool kNoPushGuardEnabled = false;

// ============================================================
// 门将「门线封堵」判定（docs/06 第 55 轮，2026-09-12 真机丢球逐帧复盘）
// ------------------------------------------------------------
// 球已经在门框内的飞行轨迹上、且马上到门线时，门将**唯一拦得到的点**是
// "门线上的预测落点"——追球的侧方点或退到门前 40cm 都来不及（真机实测两种都丢）。
// 返回 true 时把目标点写进 (tx,ty)：贴门线 3cm、y = 预测落点（夹在门框内侧）。
// 让位条件：门将已经贴到球（<kCoverLineGiveUp）→ 交给清球/推球分支（推出去更好）。
// ============================================================
bool gk_cover_line_point(const WorldModel &wm, int id, double &tx, double &ty);

// 守门员：站球门前跟球 y；球逼近时出击
void run_goalie(WorldModel &wm, int id);

// ============================================================
// ============================================================
// 门将「球外侧禁推」（docs/06 第 58 轮）：球已进我方门口（<50cm）且门将站在球的场侧时，
// 返回"先横move到球侧方 25cm"的目标点（保持球后 10cm，**绝不越过球**）；false = 不触发。
//   真机 3 场 6 个丢球全是这个机制（门将贴球从场侧追进自家门，concede_diag 前后 −7~−17cm、
//   我方最后触球 15/15 帧）。让开后（lat≥25cm）门将才允许绕到球的门侧推/走门线封堵。
// ============================================================
bool gk_side_step_point(const WorldModel &wm, int id, double &tx, double &ty);

// 射门助跑距离（cm）：球后多远开始冲，决定撞球瞬间的机头速度 ⇒ 决定出球速度
// ------------------------------------------------------------
// 常规 20cm；**罚点球 35cm**。依据（docs/06 第 57 轮，真机 09-13 rlg 帧 2292~2365）：
//   20cm 助跑出球只有 ~103cm/s，40cm 外的点球飞行 ~17 帧，门将横移 17cm 就够到（离球
//   4.4cm 时把球打偏）→ 射正也白搭；35cm 助跑让机器人到位时已近满速（实测加速度
//   658cm/s²，20cm 理论 162cm/s、35cm 214cm/s 封顶在 150 左右）→ 飞行缩到 ~12 帧。
// ============================================================
double shoot_prep_dist(const WorldModel &wm);

// 追球者（持球核心）：射门 → 传球推进 → 追球
void run_active(WorldModel &wm, int id);

// 角色执行前取消不安全的配合任务/临时控球；飞行中不按散球或重算线路取消。
void cancel_unsafe_coop_pass(WorldModel &wm);

// 防守站位：站球-门连线拦截点
void run_passive(WorldModel &wm, int id);

// 助攻跑位：站助攻参考点
void run_assist(WorldModel &wm, int id);

// 中场衔接：站中场参考点
void run_midfield(WorldModel &wm, int id);

}  // namespace simuro5
#endif
